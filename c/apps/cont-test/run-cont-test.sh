if run_group lc; then
	use_hardware lc LeastCriticalReplacementPolicy

	# The least critical policy ignores the limit value, any non-zero value sets core 0 as critical
	echo "#define CORES_RUNNING 4" > $TEST_SETTINGS_FILE
	echo "#define CONTENTION_LIMIT 1" >> $TEST_SETTINGS_FILE
	CONFIG_NAME="patmos-lc-4"
	run_benchmark
fi

if run_group lcr; then
	use_hardware lcr LeastCriticalReplacementPolicy

	# Like lc, but non-critical misses to a set with only critical lines are rejected and retried
	echo "#define CORES_RUNNING 4" > $TEST_SETTINGS_FILE
	echo "#define CONTENTION_LIMIT 1" >> $TEST_SETTINGS_FILE
	CONFIG_NAME="patmos-lcr-4"
	run_benchmark
fi

if run_group part; then
	use_hardware part CriticalWayPartitionReplacementPolicy

	# The partitioning policy uses the written value as the number of critical ways (out of 8): split k-(8-k)
	for k in 1 2 3 4 5 6 7; do
		echo "#define CORES_RUNNING 4" > $TEST_SETTINGS_FILE
		echo "#define CONTENTION_LIMIT $k" >> $TEST_SETTINGS_FILE
		CONFIG_NAME="patmos-part-4-$k"
		run_benchmark
	done
fi
