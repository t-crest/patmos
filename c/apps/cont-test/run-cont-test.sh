TEST_SETTINGS_FILE="testing_settings.h"
RESULT_FILE="cont-test-results.csv"
REPEAT=${REPEAT:-200}
FPGA=false
BUILD=true
CONFIG_GROUPS="default,cont,lc,lcr,part"

# The hardware configurations are generated from this board configuration (in patmos/hardware/config): the NoCs are
# removed and a shared L2 cache with the replacement policy of the configuration group is added
BASE_BOARD="altde2-115"
L2_CACHE='size="64K" ways="8" bytesPerBlock="64"'
PATMOS_DIR=$(cd ../../.. && pwd)
CONFIG_DIR="$PATMOS_DIR/tmp/cont-test-configs"

function usage {
	echo "Usage: $0 [--fpga] [--no-build] [--groups default,cont,lc,lcr,part]"
	echo "  --fpga      Run on the FPGA. The FPGA must already hold the hardware for the selected groups, built from"
	echo "              $CONFIG_DIR/$BASE_BOARD-l2<repl>.xml with the L2 replacement policy repl:"
	echo "              cont for default and cont, lc for lc, lcr for lcr, part for part."
	echo "  --no-build  Do not rebuild the emulator, use the installed patemu for all groups."
	echo "  --groups    Comma separated groups of configurations to run (default: $CONFIG_GROUPS)."
}

while [[ "$#" -gt 0 ]]; do
  case $1 in
    --fpga) FPGA=true ;;
    --no-build) BUILD=false ;;
    --groups) CONFIG_GROUPS="$2"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1"; usage; exit 1 ;;
  esac
  shift
done

# Prepare output file
echo "config,core0,core1,core2,core3,status" > $RESULT_FILE

function run_group {
	[[ ",$CONFIG_GROUPS," == *",$1,"* ]]
}

# Generated hardware configuration for an L2 replacement policy
# $1: replacement policy (repl attribute of the L2Cache element)
function config_file {
	echo "$CONFIG_DIR/$BASE_BOARD-l2$1.xml"
}

# Generates the hardware configuration for an L2 replacement policy from the base board configuration
# $1: replacement policy (repl attribute of the L2Cache element)
function generate_config {
	local base="$PATMOS_DIR/hardware/config/$BASE_BOARD.xml"
	local config=$(config_file $1)
	mkdir -p "$CONFIG_DIR"

	# The parent configuration is resolved relative to the configuration file, so it is made absolute
	awk -v repl="$1" -v l2="$L2_CACHE" -v base="$BASE_BOARD" -v config_dir="$PATMOS_DIR/hardware/config" '
		/<patmos / { sub(/default="/, "default=\"" config_dir "/") }
		/<description>/ { print "  <description>Generated by run-cont-test.sh from " base ".xml without NoCs and with a shared L2 cache (repl=" repl ")</description>"; next }
		/<CmpDev name="(Argo|S4NoC)"/ { next }
		/<ExtMem / && !added { print "  <L2Cache " l2 " repl=\"" repl "\"/>"; print ""; added = 1 }
		{ print }
	' "$base" > "$config"

	if ! grep -q "<L2Cache .*repl=\"$1\"" "$config" || grep -qE "Argo|S4NoC" "$config"; then
		echo "Could not generate the hardware configuration $config from $base"
		exit 1
	fi
}

CURRENT_REPL=""

# Build and install the emulator for an L2 replacement policy, unless it is already installed
# $1: replacement policy (repl attribute of the L2Cache element), $2: replacement policy module that the hardware must contain
function use_hardware {
	if [ "$FPGA" = true ] || [ "$BUILD" = false ] || [ "$1" = "$CURRENT_REPL" ]; then
		return
	fi

	generate_config $1
	echo "Building emulator with the $1 L2 replacement policy ($(config_file $1))..."
	# The Verilog is only regenerated when its marker is older than the sources, so a switch to a configuration file
	# older than the last build is otherwise skipped. Removing the marker forces the regeneration.
	rm -f ../../../hardware/buildemu/.vgen
	(cd ../../.. && make emulator BOARD=$BASE_BOARD CONFIGFILE=$(config_file $1)) || exit 1

	# The emulator make target ignores Verilator errors, so check that the expected policy was generated
	if ! grep -q "^module $2(" ../../../hardware/buildemu/Patmos.v; then
		echo "The emulator built with the $1 L2 replacement policy does not contain $2"
		exit 1
	fi
	CURRENT_REPL=$1
}

function run_benchmark {
	COUNTER=0
	while [ $COUNTER -ne $REPEAT ]
	do
		# Compile new version of program
		make

		cd ../../..

		if [ "$FPGA" = true ]; then
			# Run on FPGA
			# NOTE: The timeout utility doesnt work with the make target that well
			echo "Running on FPGA..."
			output=$(make APP=cont-test config download)
			exit_code=$?
		else
			# Run on emulator
			echo "Running on emulator..."
			output=$(timeout --kill-after=5s 60s patemu tmp/cont-test.elf)
			exit_code=$?
		fi


		if [ $exit_code -eq 124 ]; then
			echo "Timeout"
			# Timed out, just show zeros
			RESULT_LINE="0,0,0,0"
			STATUS="T"
		else
			# Output last line (results) to file
			RESULT_LINE=$(echo "$output" | tail -n 1)
			STATUS="S"
		fi

		echo "$CONFIG_NAME,$RESULT_LINE,$STATUS" >> "c/apps/cont-test/$RESULT_FILE"
		COUNTER=$(( $COUNTER + 1 ))

		cd c/apps/cont-test
	done
}

